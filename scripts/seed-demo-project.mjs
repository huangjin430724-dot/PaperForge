async function main() {
  const metaPath = path.join(projectRoot, 'project.json');
  const existed = await pathExists(projectRoot);
  await fs.mkdir(projectRoot, { recursive: true });
  const existingMeta = await readJson(metaPath, {});
  const createdAt = existingMeta.createdAt || now;
  const meta = {
    id: projectId,
    name: 'PaperForge Demo Project',
    createdAt,
    updatedAt: now,
    tags: ['demo', 'figure-agent', 'onboarding'],
    archived: false,
    trashed: false,
    trashedAt: null,
    fileOrder: {
      '': ['README_DEMO.md', 'main.tex', 'drafts', 'figures', 'refs'],
      drafts: ['source_zh.md'],
      figures: [
        'figure_plan.json',
        'demo_paperforge_research_workflow.svg',
        'demo_paperforge_research_workflow.figure.json',
        'demo_paperforge_research_workflow.figure.qa.json',
        'index.json',
        'figure_report.md'
      ],
      refs: ['reference.bib']
    }
  };

  await writeFile('project.json', JSON.stringify(meta, null, 2));
  await writeFile('README_DEMO.md', demoReadme);
  await writeFile('main.tex', mainTex);
  await writeFile('drafts/source_zh.md', sourceZh);
  await writeFile('refs/reference.bib', bib);
  await writeFile('figures/figure_plan.json', JSON.stringify(figurePlan, null, 2));
  await writeFile(assetPath, svg());
  await writeFile(packagePath, JSON.stringify(figurePackage, null, 2));
  await writeFile(qaPath, JSON.stringify(qaReport, null, 2));
  await writeFile('figures/index.json', JSON.stringify(registry, null, 2));
  await writeFile('figures/figure_report.md', figureReport);

  const action = existed ? 'updated' : 'created';
  console.log(`Demo project ${action}: ${path.relative(repoRoot, projectRoot)}`);
  console.log('Open PaperForge and select "PaperForge Demo Project" from the project list.');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
